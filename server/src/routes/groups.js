import { Router } from 'express';
import auth from '../middleware/auth.js';
import Group from '../models/Group.js';
import Post from '../models/Post.js';
import { notify } from '../realtime.js';
import { bad, isId, POST_POP, U, clean } from '../utils/helpers.js';
const r = Router();
r.param('id', (req, res, next, id) => isId(id) ? next() : bad(res, 'Invalid id'));
const sum = (g, me) => ({ ...g.toObject(), memberCount: g.members.length, isMember: g.members.some(m => String(m._id || m) === me), isAdmin: g.admins.some(m => String(m._id || m) === me) });
r.get('/', auth, async (req, res) => {
  const all = await Group.find(req.query.mine ? { members: req.userId } : {}).sort('-createdAt').limit(100);
  res.json(all.map(g => { const o = sum(g, req.userId); delete o.members; return o; }));
});
r.post('/', auth, async (req, res) => {
  if (!req.body.name?.trim()) return bad(res, 'Group name required');
  const g = await Group.create({ ...clean(req.body, ['name', 'description', 'cover', 'privacy']), owner: req.userId, admins: [req.userId], members: [req.userId] });
  res.status(201).json(sum(g, req.userId));
});
r.get('/:id', auth, async (req, res) => { const g = await Group.findById(req.params.id).populate('members admins owner', U); if (!g) return bad(res, 'Group not found', 404); res.json(sum(g, req.userId)); });
r.put('/:id', auth, async (req, res) => { const g = await Group.findById(req.params.id); if (!g?.admins.map(String).includes(req.userId)) return bad(res, 'Admins only', 403);
  Object.assign(g, clean(req.body, ['name', 'description', 'cover', 'privacy'])); await g.save(); res.json(sum(g, req.userId)); });
r.post('/:id/join', auth, async (req, res) => { const g = await Group.findByIdAndUpdate(req.params.id, { $addToSet: { members: req.userId } }, { new: true }); if (!g) return bad(res, 'Group not found', 404);
  g.admins.forEach(a => notify(a, req.userId, 'group_join', null, { link: `/groups/${g._id}`, text: g.name })); res.json(sum(g, req.userId)); });
r.post('/:id/leave', auth, async (req, res) => { const g = await Group.findById(req.params.id); if (!g) return bad(res, 'Group not found', 404);
  if (String(g.owner) === req.userId) return bad(res, 'The owner can\u2019t leave the group');
  g.members.pull(req.userId); g.admins.pull(req.userId); await g.save(); res.json(sum(g, req.userId)); });
r.post('/:id/admins/:uid', auth, async (req, res) => { const g = await Group.findById(req.params.id); if (!g?.admins.map(String).includes(req.userId)) return bad(res, 'Admins only', 403);
  const uid = req.params.uid; if (!g.members.map(String).includes(uid)) return bad(res, 'Not a member');
  g.admins.map(String).includes(uid) ? (String(g.owner) !== uid && g.admins.pull(uid)) : (g.admins.push(uid), notify(uid, req.userId, 'group_admin', null, { link: `/groups/${g._id}`, text: g.name }));
  await g.save(); res.json(sum(await g.populate('members admins owner', U), req.userId)); });
r.delete('/:id/members/:uid', auth, async (req, res) => { const g = await Group.findById(req.params.id); if (!g?.admins.map(String).includes(req.userId)) return bad(res, 'Admins only', 403);
  if (String(g.owner) === req.params.uid) return bad(res, 'Can\u2019t remove the owner');
  g.members.pull(req.params.uid); g.admins.pull(req.params.uid); await g.save(); res.json(sum(await g.populate('members admins owner', U), req.userId)); });
r.get('/:id/posts', auth, async (req, res) => { const g = await Group.findById(req.params.id); if (!g) return bad(res, 'Group not found', 404);
  if (g.privacy === 'private' && !g.members.map(String).includes(req.userId)) return res.json([]);
  res.json(await Post.find({ group: g._id }).sort('-createdAt').limit(50).populate(POST_POP)); });
r.delete('/:id', auth, async (req, res) => { const g = await Group.findById(req.params.id); if (String(g?.owner) !== req.userId) return bad(res, 'Owner only', 403);
  await Post.deleteMany({ group: g._id }); await g.deleteOne(); res.json({ ok: true }); });
export default r;
